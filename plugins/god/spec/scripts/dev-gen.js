#!/usr/bin/env node
/**
 * dev-gen.js — spec → 代码骨架（roadmap G5）
 *
 * 用法:
 *   node dev-gen.js <项目目录>
 *     读 spec/spec.feature → 写 src/<feature>.js
 *
 *   node dev-gen.js <项目目录> --dry-run
 *     预览，不写文件
 *
 *   node dev-gen.js <项目目录> --force
 *     覆盖已有 src/<feature>.js 不询问
 *
 * 设计依据: docs/rfcs/0007-dev-gen.md
 * 零外部依赖，纯 Node 内置模块。
 */

'use strict';

const fs = require('fs');
const path = require('path');

function readFileSafe(p) {
  try { return fs.readFileSync(p, 'utf8'); } catch { return null; }
}
function findSpecDir(projectDir) {
  if (fs.existsSync(path.join(projectDir, 'spec', 'spec.feature'))) {
    return path.join(projectDir, 'spec');
  }
  if (fs.existsSync(path.join(projectDir, 'spec.feature'))) {
    return projectDir;
  }
  return null;
}

function parseFeatureScenarios(specContent) {
  // 解析 @SC-xxx + Scenario: <名> + Given/When/Then
  const lines = specContent.split('\n');
  const scenarios = [];
  let current = null;
  for (const line of lines) {
    const tagMatch = line.match(/^\s*@(SC-\d{3})\b/);
    if (tagMatch) {
      if (current) scenarios.push(current);
      current = { id: tagMatch[1], name: '', gwt: [] };
    } else if (current) {
      const nameMatch = line.match(/^\s*Scenario:\s*(.+)$/);
      if (nameMatch) {
        current.name = nameMatch[1].trim();
      } else {
        const gwtMatch = line.match(/^\s*(Given|When|Then|And|But)\s+(.+)$/);
        if (gwtMatch) {
          current.gwt.push({ keyword: gwtMatch[1], text: gwtMatch[2].trim() });
        }
      }
    }
  }
  if (current) scenarios.push(current);
  return scenarios;
}

function getFeatureSlug(specDir, meta) {
  if (meta && meta.specId) {
    return meta.specId.replace(/[^a-zA-Z0-9-]/g, '-').toLowerCase();
  }
  // 退路：从 sources.md 第一行 H1 拿
  const sources = readFileSafe(path.join(specDir, 'sources.md'));
  if (sources) {
    const h1 = sources.match(/^#\s+(.+)$/m);
    if (h1) return h1[1].trim().replace(/[^a-zA-Z0-9一-龥-]/g, '-').toLowerCase();
  }
  return 'feature';
}

function isTypeScriptProject(projectDir) {
  return fs.existsSync(path.join(projectDir, 'tsconfig.json'));
}

function generateSkeleton(scenarios, featureSlug, useTs) {
  const ext = useTs ? 'ts' : 'js';
  const exportKeyword = useTs ? 'export' : 'module.exports';
  const funcKeyword = useTs ? 'export function' : 'function';

  let code = '';
  code += `/**\n`;
  code += ` * ${featureSlug} — spec skeleton\n`;
  code += ` * Auto-generated by god dev-gen. Edit implementations; do not remove @spec annotations.\n`;
  code += ` */\n\n`;

  if (useTs) {
    code += `// TypeScript project detected\n\n`;
  }

  for (const sc of scenarios) {
    const num = sc.id.replace('SC-', '').replace(/^0+/, '') || sc.id.replace('SC-', '');
    const funcName = `sc${num}`;
    code += `/**\n`;
    code += ` * ${sc.name}\n`;
    code += ` * @spec ${sc.id}\n`;
    if (sc.name) code += ` * @scenario ${sc.name}\n`;
    code += ` */\n`;
    code += `${funcKeyword} ${funcName}() {\n`;
    code += `  // TODO: implement ${sc.id} — ${sc.name}\n`;
    for (const g of sc.gwt) {
      code += `  //   ${g.keyword}: ${g.text}\n`;
    }
    code += `}\n\n`;
  }

  return { code, ext };
}

function main() {
  const projectDir = process.argv[2];
  if (!projectDir) {
    console.error('用法: node dev-gen.js <项目目录> [--dry-run] [--force]');
    process.exit(1);
  }
  if (!fs.existsSync(projectDir)) {
    console.error(`✗ 项目目录不存在: ${projectDir}`);
    process.exit(1);
  }
  const opts = {
    dryRun: process.argv.includes('--dry-run'),
    force: process.argv.includes('--force'),
  };

  const specDir = findSpecDir(projectDir);
  if (!specDir) {
    console.error('✗ 找不到 spec 目录');
    process.exit(1);
  }
  const specContent = readFileSafe(path.join(specDir, 'spec.feature'));
  if (!specContent) {
    console.error('✗ 找不到 spec.feature');
    process.exit(1);
  }
  const metaContent = readFileSafe(path.join(specDir, 'meta.json'));
  const meta = metaContent ? JSON.parse(metaContent) : null;
  const featureSlug = getFeatureSlug(specDir, meta);
  const useTs = isTypeScriptProject(projectDir);
  const scenarios = parseFeatureScenarios(specContent);

  if (scenarios.length === 0) {
    console.error('✗ spec.feature 无 SC 解析');
    process.exit(1);
  }

  const { code, ext } = generateSkeleton(scenarios, featureSlug, useTs);
  const srcDir = path.join(projectDir, 'src');
  const outPath = path.join(srcDir, `${featureSlug}.${ext}`);

  if (opts.dryRun) {
    console.log(`[dry-run] 将写：${outPath}\n`);
    console.log('--- 骨架预览 ---');
    console.log(code);
    return;
  }

  if (fs.existsSync(outPath) && !opts.force) {
    console.error(`✗ ${outPath} 已存在（用 --force 覆盖）`);
    process.exit(1);
  }

  fs.mkdirSync(srcDir, { recursive: true });
  // 写失败回滚
  let backup = null;
  if (fs.existsSync(outPath)) {
    backup = fs.readFileSync(outPath, 'utf8');
  }
  try {
    fs.writeFileSync(outPath, code, 'utf8');
  } catch (e) {
    if (backup !== null) fs.writeFileSync(outPath, backup);
    throw e;
  }

  console.log(`✓ dev-gen 完成：${outPath}`);
  console.log(`  feature: ${featureSlug}`);
  console.log(`  language: ${useTs ? 'TypeScript' : 'JavaScript'}`);
  console.log(`  scenarios: ${scenarios.length} (${scenarios.map(s => s.id).join(', ')})`);
  console.log(`  size: ${(code.length / 1024).toFixed(1)} KB`);
  console.log(`\n下一步：跑 spec-validate.js #7 确认 @spec 标注通过`);
}

if (require.main !== module) {
  module.exports = {
    parseFeatureScenarios,
    getFeatureSlug,
    isTypeScriptProject,
    generateSkeleton,
  };
} else {
  main();
}
